      if (!/class\s*=\s*"[^"]*\btitle3\b/i.test(block)) continue;
      const anchor = anchorTags(block)[0];
      if (!anchor) continue;
      const match = hrefRe.exec(attributeOf(anchor, "href") ?? "");
      if (!match) continue;
